"""ER diagram (Mermaid erDiagram) of the schema built by db/migrations, read from the live catalog.

Base tables only (partitions, staging tables, schema_migrations and PostGIS's spatial_ref_sys left out; materialized views listed in a
comment). Columns with simplified types, PK / FK / UK markers; one relationship per foreign key, with
cardinality from the FK columns: NOT NULL -> exactly one parent (||), nullable -> zero or one (|o); unique FK
columns -> one child (o|), otherwise many (o{).
Usage: make er (needs the stack running). Writes report/er-diagram.mmd.
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "report" / "er-diagram.mmd"

SQL = r"""
WITH t AS (
  SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND NOT c.relispartition
    AND c.relname NOT LIKE 'stg\_%' AND c.relname NOT IN ('schema_migrations', 'spatial_ref_sys')),
cols AS (
  SELECT t.relname, a.attnum, a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull
  FROM t JOIN pg_attribute a ON a.attrelid = t.oid WHERE a.attnum > 0 AND NOT a.attisdropped),
cons AS (
  SELECT t.relname, k.contype, k.conkey, k.confrelid::regclass::text AS ref, k.confkey
  FROM t JOIN pg_constraint k ON k.conrelid = t.oid WHERE k.contype IN ('p', 'f', 'u'))
SELECT json_build_object(
  'columns', (SELECT json_agg(cols ORDER BY relname, attnum) FROM cols),
  'constraints', (SELECT json_agg(cons) FROM cons),
  'views', (SELECT json_agg(matviewname ORDER BY matviewname) FROM pg_matviews WHERE schemaname = 'public'))
"""


def simplify(t: str) -> str:
    t = re.sub(r"\(.*\)", "", t).strip()
    return {"timestamp with time zone": "timestamptz", "character": "char", "character varying": "varchar",
            "double precision": "float8", "USER-DEFINED": "enum"}.get(t, t).replace(" ", "_")


def main() -> int:
    raw = subprocess.run(["docker", "compose", "exec", "-T", "db", "psql", "-U", "landlens_owner", "-d",
                          "landlens_owner", "-At", "-c", SQL], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    d = json.loads(raw)
    tables: dict[str, list[dict]] = {}
    for c in d["columns"]:
        tables.setdefault(c["relname"], []).append(c)
    pk, uk, fk_cols, rels = {}, {}, {}, []
    for k in d["constraints"]:
        names = {c["attnum"]: c["attname"] for c in tables[k["relname"]]}
        cols = [names[n] for n in k["conkey"]]
        if k["contype"] == "p":
            pk.setdefault(k["relname"], set()).update(cols)
        elif k["contype"] == "u":
            uk.setdefault(k["relname"], []).append(set(cols))
        else:
            fk_cols.setdefault(k["relname"], set()).update(cols)
            notnull = all(next(c for c in tables[k["relname"]] if c["attname"] == n)["attnotnull"] for n in cols)
            unique = set(cols) == pk.get(k["relname"], set()) or set(cols) in uk.get(k["relname"], [])
            rels.append((k["ref"], k["relname"], notnull, unique, ", ".join(cols)))
    # pk/uk may be filled after an fk of the same table was seen: recompute uniqueness
    rels = [(p, c, nn, set(cols.split(", ")) == pk.get(c, set()) or set(cols.split(", ")) in uk.get(c, []), cols)
            for p, c, nn, _, cols in rels]
    lines = ["%% LandLens ER diagram, generated by scripts/er_diagram.py from the migrated schema (make er).",
             f"%% Materialized views (read models, not entities): {', '.join(d['views'] or [])}",
             "erDiagram"]
    for name in sorted(tables):
        lines.append(f"  {name} {{")
        for c in tables[name]:
            marks = []
            if c["attname"] in pk.get(name, set()):
                marks.append("PK")
            if c["attname"] in fk_cols.get(name, set()):
                marks.append("FK")
            if any(c["attname"] in u and len(u) == 1 for u in uk.get(name, [])):
                marks.append("UK")
            lines.append(f"    {simplify(c['type'])} {c['attname']}{(' ' + ','.join(marks)) if marks else ''}")
        lines.append("  }")
    for parent, child, notnull, unique, cols in sorted(rels):
        left = "||" if notnull else "|o"
        right = "o|" if unique else "o{"
        lines.append(f'  {parent} {left}--{right} {child} : "{cols}"')
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(tables)} tables, {len(rels)} relationships")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
